#!/usr/bin/env python3
"""Create (or refresh) the paperweight patcher project for one Minecraft version.

Each supported Minecraft version lives in ``versions/<mc>/`` as an independent
Gradle build, because Paper itself maintains one branch per version and the
required JDK, Gradle and paperweight versions differ between them.  The
generated files follow the official PaperMC fork template
(https://github.com/PaperMC/paperweight-examples, branch ``v2-fork``).

Usage
-----
    python3 scripts/fork/scaffold_version.py \
        --paper-checkout /path/to/Paper --ref <commit> --mc 26.2 \
        --java 25 --paperweight 2.0.0-beta.21 --channel ALPHA [--legacy-versioning]

The Gradle wrapper (jar, properties and scripts) is copied verbatim from the
Paper commit so that the fork always builds with the same Gradle version as
its upstream.  Afterwards run ``generate_patches.py`` for the same ref.
"""

from __future__ import annotations

import argparse
import pathlib
import stat
import subprocess
import sys

BUILD_GRADLE = """import org.gradle.api.tasks.testing.logging.TestExceptionFormat
import org.gradle.api.tasks.testing.logging.TestLogEvent

// Lemon - Paper fork for Minecraft {mc}.
// Generated by scripts/fork/scaffold_version.py from the official PaperMC fork
// template (paperweight-examples, v2-fork). Do not edit by hand without also
// updating the generator.

plugins {{
    id("io.papermc.paperweight.patcher") version "{paperweight}"
}}

paperweight {{
    upstreams.paper {{
        ref = providers.gradleProperty("paperRef")

        patchFile {{
            path = "paper-server/build.gradle.kts"
            outputFile = file("lemon-server/build.gradle.kts")
            patchFile = file("lemon-server/build.gradle.kts.patch")
        }}
        patchFile {{
            path = "paper-api/build.gradle.kts"
            outputFile = file("lemon-api/build.gradle.kts")
            patchFile = file("lemon-api/build.gradle.kts.patch")
        }}
        patchDir("paperApi") {{
            upstreamPath = "paper-api"
            excludes = setOf("build.gradle.kts")
            patchesDir = file("lemon-api/paper-patches")
            outputDir = file("paper-api")
        }}
    }}
}}

subprojects {{
    apply(plugin = "java-library")
    apply(plugin = "maven-publish")

    extensions.configure<JavaPluginExtension> {{
        toolchain {{
            languageVersion = JavaLanguageVersion.of({java})
        }}
    }}
}}

val paperMavenPublicUrl = "https://repo.papermc.io/repository/maven-public/"

subprojects {{
    tasks.withType<JavaCompile>().configureEach {{
        options.encoding = Charsets.UTF_8.name()
        options.release = {java}
        options.isFork = true
        options.compilerArgs.addAll(listOf("-Xlint:-deprecation", "-Xlint:-removal"))
    }}
    tasks.withType<Javadoc>().configureEach {{
        options.encoding = Charsets.UTF_8.name()
    }}
    tasks.withType<ProcessResources>().configureEach {{
        filteringCharset = Charsets.UTF_8.name()
    }}
    tasks.withType<Test>().configureEach {{
        testLogging {{
            showStackTraces = true
            exceptionFormat = TestExceptionFormat.FULL
            events(TestLogEvent.STANDARD_OUT)
        }}
    }}
    tasks.withType<AbstractArchiveTask>().configureEach {{
        isPreserveFileTimestamps = false
        isReproducibleFileOrder = true
    }}

    repositories {{
        mavenCentral()
        maven(paperMavenPublicUrl)
    }}

    // Only local publication is configured. No credentials are stored in this
    // repository; add your own repository via an init script or CI secrets.
}}
"""

SETTINGS_HEADER = """pluginManagement {
    repositories {
        gradlePluginPortal()
        maven("https://repo.papermc.io/repository/maven-public/")
    }
}

plugins {
    id("org.gradle.toolchains.foojay-resolver-convention") version "1.0.0"
}

rootProject.name = "lemon"

for (name in listOf("lemon-api", "lemon-server")) {
    include(name)
    file(name).mkdirs()
}
"""

SETTINGS_VERSIONING = """
gradle.lifecycle.beforeProject {
    val mcVersion = providers.gradleProperty("mcVersion").get().trim()
    val channel = providers.gradleProperty("channel").get().trim()
    val buildNumber = providers.environmentVariable("BUILD_NUMBER").orNull?.trim()?.toInt()
    version = if (buildNumber == null) {
        "$mcVersion.local-SNAPSHOT"
    } else {
        "$mcVersion.build.$buildNumber-${channel.lowercase()}"
    }
}
"""

GRADLE_PROPERTIES = """group=dev.lemonpvp.lemon
{version_line}mcVersion={mc}
apiVersion={mc}
channel={channel}
# Pinned upstream Paper commit (branch {branch}). Update via docs/UPSTREAM-SYNC.md.
paperRef={ref}

org.gradle.configuration-cache=true
org.gradle.caching=true
org.gradle.parallel=true
org.gradle.vfs.watch=false
org.gradle.jvmargs=-Xmx3G
"""

GITIGNORE = """.gradle
build
/run

/lemon-server/build.gradle.kts
/lemon-server/src/minecraft
/paper-server
/lemon-api/build.gradle.kts
/paper-api
/paper-api-generator

.idea/
"""

WRAPPER_FILES = ("gradlew", "gradlew.bat", "gradle/wrapper/gradle-wrapper.jar", "gradle/wrapper/gradle-wrapper.properties")


def git_show_bytes(checkout: pathlib.Path, ref: str, path: str) -> bytes:
    return subprocess.run(["git", "-C", str(checkout), "show", f"{ref}:{path}"], check=True, capture_output=True).stdout


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--paper-checkout", required=True, type=pathlib.Path)
    p.add_argument("--ref", required=True)
    p.add_argument("--branch", required=True, help="upstream branch the ref belongs to (documentation only)")
    p.add_argument("--mc", required=True)
    p.add_argument("--java", required=True, type=int)
    p.add_argument("--paperweight", required=True)
    p.add_argument("--channel", default="ALPHA")
    p.add_argument("--legacy-versioning", action="store_true",
                   help="use <mc>-R0.1-SNAPSHOT style versioning (Paper <= 1.21.11)")
    p.add_argument("--out", type=pathlib.Path, default=None)
    a = p.parse_args()

    out = a.out or pathlib.Path("versions") / a.mc
    out.mkdir(parents=True, exist_ok=True)

    (out / "build.gradle.kts").write_text(
        BUILD_GRADLE.format(mc=a.mc, paperweight=a.paperweight, java=a.java), encoding="utf-8")
    settings = SETTINGS_HEADER + ("" if a.legacy_versioning else SETTINGS_VERSIONING)
    (out / "settings.gradle.kts").write_text(settings, encoding="utf-8")
    version_line = f"version={a.mc}-R0.1-SNAPSHOT\n" if a.legacy_versioning else ""
    (out / "gradle.properties").write_text(
        GRADLE_PROPERTIES.format(mc=a.mc, channel=a.channel, ref=a.ref, branch=a.branch, version_line=version_line),
        encoding="utf-8")
    (out / ".gitignore").write_text(GITIGNORE, encoding="utf-8")

    for f in WRAPPER_FILES:
        target = out / f
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(git_show_bytes(a.paper_checkout, a.ref, f))
    gradlew = out / "gradlew"
    gradlew.chmod(gradlew.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"scaffolded {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
